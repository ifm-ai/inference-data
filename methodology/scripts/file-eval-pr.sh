#!/usr/bin/env bash
# File one PR into ifm-ai/inference-perf-data for a single model.
#
#   ./file-eval-pr.sh <slug>
#
# Adds eval-data-<slug>/ containing the raw dataset (data/), the per-test report
# (README.md), the per-model chart, a manifest and a gate record.
# Idempotent: exits 0 if the branch already exists on the remote.
set -euo pipefail

SLUG="${1:?slug required}"
# REPO_DIR lets each parallel worker use its own clone; git checkout -B in a
# shared clone would race between workers.
REPO="${REPO_DIR:-/mnt/Projects/inference-perf-data}"
STAGING=/mnt/Projects/k2-perf-staging
GHREPO=ifm-ai/inference-perf-data
DIR="eval-data-$SLUG"
BRANCH="eval/$SLUG"

SRC="$STAGING/$DIR"
[ -d "$SRC" ] || { echo "MISSING staged dir: $SRC" >&2; exit 2; }

py() { python3 -c "
import json
d=json.load(open('$SRC/$1'))
$2"; }

LABEL=$(py data/results.json "print(d['label'])")
MODEL=$(py data/results.json "print(d['model'])")
FAMILY=$(py data/results.json "print(d['family'])")
SIZE=$(py data/results.json "v=d['size_gib'];print('—' if v is None else f'{v} GiB')")
MEAN=$(py data/results.json "v=d['mean_over_7'];print('n/a' if v is None else f'{v:.3f}')")
TPS=$(py data/results.json "v=(d.get('throughput') or {}).get('decode_tok_per_s');print('—' if v is None else f'{v} tok/s')")
NITEMS=$(py audit.json "print(d['sampled_items'])")

if git -C "$REPO" ls-remote --exit-code --heads origin "$BRANCH" >/dev/null 2>&1; then
  echo "SKIP $BRANCH already on remote"
  exit 0
fi

cd "$REPO"
git fetch -q origin main
git checkout -q -B "$BRANCH" origin/main

rm -rf "$DIR"
cp -r "$SRC" "$DIR"
git add "$DIR"

BODY="Benchmark dataset and per-test report for **$LABEL** (\`$MODEL\`).

| | |
|---|---|
| Family | $FAMILY |
| Size | $SIZE |
| Mean over 7 tasks | $MEAN |
| Decode throughput | $TPS |
| Sampled items | $NITEMS |

**Contents**

| Path | Contents |
|---|---|
| \`README.md\` | per-test report: score, stderr and n for each task, plus context |
| \`model-scores.png\` | per-task scores vs the 7B baseline and the study best |
| \`data/results.json\` | consolidated lm-eval results, harness provenance, raw per-filter metrics |
| \`data/samples.jsonl\` | every evaluated item: prompt, model output, target, per-item score |
| \`data/throughput.json\` | fixed-prompt decode/prefill probe |
| \`manifest.json\` | lineage and per-task metric record |
| \`audit.json\` | packaging gate record |

**Measurement class.** This is a \`cpu_quality_eval\` dataset — accuracy on 8
lm-eval tasks plus single-stream CPU throughput, produced on a CPU-only host with
the IFM K2-Horizon llama.cpp backend. It is **not** a GPU throughput sweep and is
not interchangeable with the \`perf-data-*\` series in this repository.

**Statistical caveat.** n=12 per task, so the per-task standard error is roughly
±0.08–0.15 and the 7-task mean carries about ±0.03–0.05. This dataset does not
resolve differences smaller than that. See the summary PR for the cross-model
report and \`methodology/\` for harness configuration and limits.

Generated by the scripts in \`methodology/scripts/\`."

TITLE="eval-data($SLUG): CPU quality-eval dataset + per-test report for $LABEL"

git -c user.name="mvillmow" -c user.email="mvillmow@users.noreply.github.com" \
    commit -q -m "$TITLE" -m "$BODY"
git push -q -u origin "$BRANCH"

URL=$(gh pr create --repo "$GHREPO" --base main --head "$BRANCH" \
        --title "$TITLE" --body "$BODY" 2>&1 | grep -Eo 'https://github.com/[^ ]+/pull/[0-9]+' | tail -n 1)
echo "OK $SLUG -> ${URL:-<branch pushed, PR creation failed>}"
